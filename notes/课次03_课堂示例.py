import numpy as np

# ① 由列表创建
a = np.array([1, 2, 3, 4, 5])
print(a, '| shape:', a.shape)

# ② arange：指定步长，不含终点
print(np.arange(0, 10, 2))        # [0 2 4 6 8]

# ③ linspace：指定个数，含终点
print(np.linspace(0, 10, 5))      # [ 0.   2.5  5.   7.5 10. ]

# ④ 特殊矩阵
print(np.zeros((2, 3)))          # 全零
print(np.ones((2, 3)))           # 全一
print(np.identity(3))            # 单位阵

# ============================================================
# 1.2 数组运算（PPT 第 13–14 页）
# ============================================================

x = np.array([1, 2, 3])

print(x * 2)          # 每个元素 ×2 → [2 4 6]
print(x + 10)         # 每个元素 +10 → [11 12 13]
print(x * x)          # 对应元素相乘 → [1 4 9]
print(x.sum())        # 6

# ============================================================
# 1.3 元素访问与切片（PPT 第 15–17 页）
# ============================================================

b = np.array([[1, 2, 3],
              [4, 5, 6]])
print(b[0, 2])     # 第 0 行第 2 列 → 3
print(b[1, :])     # 第 1 行全部 → [4 5 6]
print(b[:, 1])     # 第 1 列全部 → [2 5]

a = np.array([10, 20, 30, 40, 50])
print(a[1:4])      # 下标 1~3 → [20 30 40]（end 取不到）
print(a[::-1])     # 逆序 → [50 40 30 20 10]
print(a[::2])      # 隔一个取 → [10 30 50]

